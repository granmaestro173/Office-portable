TYPES = {
    'word': '#2B5FB4',
    'cell': '#1E7B4A',
    'slide': '#C9481F',
    'pdf': '#D0302A',
    'other': '#6B7280',
}

W = '#FFFFFF'


def glyph(kind):
    if kind in ('word', 'other'):
        return [fill(rrect(15, 19, 19, 2.6, 1.3), W), fill(rrect(15, 24.5, 19, 2.6, 1.3), W),
                fill(rrect(15, 30, 19, 2.6, 1.3), W), fill(rrect(15, 35.5, 12, 2.6, 1.3), W)]
    if kind == 'cell':
        return [stroke(rrect(14.5, 19.5, 20, 17.5, 2), W, 2.2),
                stroke('M14.5,25.4 H34.5 M14.5,31.2 H34.5 M21.5,19.5 V37', W, 2.2)]
    if kind == 'slide':
        return [stroke(rrect(13.5, 20, 22, 15, 2), W, 2.2),
                fill(rrect(18, 28.5, 3, 3.5, 0.8), W), fill(rrect(23, 25, 3, 7, 0.8), W),
                fill(rrect(28, 26.8, 3, 5.2, 0.8), W),
                stroke('M24.5,35 V39 M20.5,39.5 H28.5', W, 2.0)]
    if kind == 'pdf':
        return [fill(text_path('PDF', 24.5, 34, 9.2), W)]
    raise ValueError(kind)


def file_icon(kind):
    c = TYPES[kind]
    return [fill(PAGE, c), fill(FOLD, mix(c, '#FFFFFF', 0.45))] + glyph(kind)


def plus_badge(kind):
    # A white disc with a colored plus, bottom-right: "new ..." tiles.
    c = TYPES[kind]
    return [fill(circle(38, 38, 9.5), '#FFFFFF'), fill(circle(38, 38, 7.8), c),
            stroke('M38,34.2 V41.8 M34.2,38 H41.8', W, 2.2)]


