# ---- launcher icon (108 viewport, safe zone = circle r33 at center) -----------

# Page used by the launcher layers: 26 x 40, bottom-center at (57, 74).
LPAGE = 'M47,34 H61 L70,43 V71 A3,3 0 0 1 67,74 H47 A3,3 0 0 1 44,71 V37 A3,3 0 0 1 47,34 Z'
LFOLD = 'M61,34 L70,43 H64 A3,3 0 0 1 61,40 Z'
LLINES = ((49, 16), (54.5, 16), (60, 16), (65.5, 10))


def launcher(sx=0, sy=0):
    def card(color, rot, dx, extra):
        layers = [fill(LPAGE, color), fill(LFOLD, mix(color, '#FFFFFF', 0.45))] + extra
        t = {'pivotX': 57, 'pivotY': 74, 'rotation': rot, 'translateX': dx - 3 - sx}
        if sy:
            t['translateY'] = -sy
        return (t, layers)

    grid = [stroke('M48.5,50 H65.5 M48.5,56.5 H65.5 M48.5,63 H65.5 M54.5,45 V69', W, 2.2)]
    bars = [fill(rrect(49, 59, 3.4, 9, 0.8), W), fill(rrect(55.3, 53, 3.4, 15, 0.8), W),
            fill(rrect(61.6, 56, 3.4, 12, 0.8), W)]
    lines = [fill(rrect(49, y, w, 2.6, 1.3), W) for y, w in LLINES]
    return [card(TYPES['cell'], -16, -6, grid), card(TYPES['slide'], 16, 6, bars), card(TYPES['word'], 0, 0, lines)]


def launcher_mono():
    # Themed icons use alpha only, so the lines are holes in the page.
    holes = ''.join(rrect(49, y, w, 2.6, 1.3) for y, w in LLINES)
    layer = fill(LPAGE + ' ' + holes, '#FFFFFFFF')
    layer['evenodd'] = True
    return [({'translateX': -3}, [layer])]


def empty_art():
    # Three file cards fanned out, for the empty "Recent" list.
    groups = []
    for kind, rot, dx, dy in (('cell', -16, -20, 6), ('slide', 16, 20, 6), ('word', 0, 0, 0)):
        layers = file_icon(kind)
        groups.append(({'pivotX': 24, 'pivotY': 44, 'rotation': rot, 'scaleX': 1.3, 'scaleY': 1.3,
                        'translateX': dx + 35, 'translateY': dy + 40}, layers))
    return groups


def main():
    os.makedirs(OUT, exist_ok=True)
    if PREVIEW:
        os.makedirs(PREVIEW, exist_ok=True)
    for kind in TYPES:
        emit('ic_file_' + kind, 40, 48, file_icon(kind))
    for kind in ('word', 'cell', 'slide'):
        emit('ic_new_' + kind, 48, 48, file_icon(kind) + plus_badge(kind))
    for name, layers in UI.items():
        emit(name, 24, 24, layers, tint='?android:attr/textColorPrimary')
    emit('ic_launcher_fg', 108, 108, launcher())
    emit('ic_launcher_mono', 108, 108, launcher_mono())
    # The same mark without the adaptive-icon margins, for use inside the app.
    emit('ic_logo', 40, 60, launcher(sx=23, sy=25))
    emit('art_empty', 120, 120, empty_art())


if __name__ == '__main__':
    main()
