#!/usr/bin/env python3
"""Generates the app's vector icons (Android VectorDrawable XML) and SVG previews.

Each icon is described once, as SVG-style paths, and written both ways so the
preview you look at is exactly what ships.

    python3 scripts/gen-icons.py [preview_dir]

Writes android/app/src/main/res/drawable/*.xml. The "PDF" lettering comes from
Inter Bold (SIL OFL) and is converted to plain path data, so no font ships.
"""
import os
import sys
from xml.sax.saxutils import quoteattr

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'android', 'app', 'src', 'main', 'res', 'drawable')
PREVIEW = sys.argv[1] if len(sys.argv) > 1 else None
INTER_BOLD = '/usr/share/fonts/opentype/inter/Inter-Bold.otf'


def text_path(text, x_center, baseline, height):
    """Outline of `text` in Inter Bold, cap height `height`, centered on x."""
    from fontTools.ttLib import TTFont
    from fontTools.pens.svgPathPen import SVGPathPen
    from fontTools.pens.transformPen import TransformPen
    from fontTools.pens.boundsPen import BoundsPen
    font = TTFont(INTER_BOLD)
    gs = font.getGlyphSet()
    cmap = font.getBestCmap()
    cap = font['OS/2'].sCapHeight
    scale = height / cap
    # Measure.
    names = [cmap[ord(c)] for c in text]
    advance = sum(gs[n].width for n in names)
    bp = BoundsPen(gs)
    x = 0
    for n in names:
        gs[n].draw(TransformPen(bp, (1, 0, 0, 1, x, 0)))
        x += gs[n].width
    xmin, _, xmax, _ = bp.bounds
    width = (xmax - xmin) * scale
    left = x_center - width / 2 - xmin * scale
    pen = SVGPathPen(gs, ntos=lambda v: ('%.2f' % v).rstrip('0').rstrip('.'))
    x = 0
    for n in names:
        # Flip y: font units go up, drawables go down.
        gs[n].draw(TransformPen(pen, (scale, 0, 0, -scale, left + x * scale, baseline)))
        x += gs[n].width
    return pen.getCommands()


# ---- primitives ---------------------------------------------------------------
# A layer is a dict: d, fill or stroke (+ width), optional alpha.

def fill(d, color, alpha=None):
    return {'d': d, 'fill': color, 'alpha': alpha}


def stroke(d, color, width=2.0, alpha=None):
    return {'d': d, 'stroke': color, 'width': width, 'alpha': alpha}


def circle(cx, cy, r):
    return 'M%s,%s m-%s,0 a%s,%s 0 1,0 %s,0 a%s,%s 0 1,0 -%s,0z' % (cx, cy, r, r, r, 2 * r, r, r, 2 * r)


def rrect(x, y, w, h, r):
    return ('M%s,%s h%s a%s,%s 0 0 1 %s,%s v%s a%s,%s 0 0 1 -%s,%s h-%s a%s,%s 0 0 1 -%s,-%s v-%s a%s,%s 0 0 1 %s,-%s z'
            % (x + r, y, w - 2 * r, r, r, r, r, h - 2 * r, r, r, r, r, w - 2 * r, r, r, r, r, h - 2 * r, r, r, r, r))


def mix(hex_color, other, t):
    a = [int(hex_color[i:i + 2], 16) for i in (1, 3, 5)]
    b = [int(other[i:i + 2], 16) for i in (1, 3, 5)]
    return '#%02X%02X%02X' % tuple(round(x + (y - x) * t) for x, y in zip(a, b))


# ---- writers ------------------------------------------------------------------

def vector_xml(size_dp, viewport, groups, tint=None):
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- Generated by scripts/gen-icons.py; edit there. -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="%sdp" android:height="%sdp"' % (size_dp, size_dp),
           '    android:viewportWidth="%s" android:viewportHeight="%s"%s>' % (
               viewport, viewport, ('\n    android:tint=' + quoteattr(tint)) if tint else '')]
    for transform, layers in groups:
        indent = '    '
        if transform:
            attrs = ' '.join('android:%s="%s"' % kv for kv in transform.items())
            out.append('    <group %s>' % attrs)
            indent = '        '
        for l in layers:
            a = ['android:pathData=%s' % quoteattr(l['d'])]
            if 'fill' in l:
                a.append('android:fillColor="%s"' % l['fill'])
                if l.get('evenodd'):
                    a.append('android:fillType="evenOdd"')
                if l.get('alpha') is not None:
                    a.append('android:fillAlpha="%s"' % l['alpha'])
            else:
                a += ['android:strokeColor="%s"' % l['stroke'], 'android:strokeWidth="%s"' % l['width'],
                      'android:strokeLineCap="round"', 'android:strokeLineJoin="round"']
                if l.get('alpha') is not None:
                    a.append('android:strokeAlpha="%s"' % l['alpha'])
            out.append(indent + '<path ' + ('\n' + indent + '    ').join(a) + ' />')
        if transform:
            out.append('    </group>')
    out.append('</vector>')
    return '\n'.join(out) + '\n'


def svg(viewport, groups, preview_color='#1B1F24'):
    out = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %s %s" width="%s" height="%s">' % (
        viewport, viewport, viewport * 4, viewport * 4)]
    for transform, layers in groups:
        if transform:
            px, py = transform.get('pivotX', 0), transform.get('pivotY', 0)
            t = 'translate(%s %s) rotate(%s %s %s) scale(%s %s)' % (
                transform.get('translateX', 0), transform.get('translateY', 0),
                transform.get('rotation', 0), px, py, transform.get('scaleX', 1), transform.get('scaleY', 1))
            # Android: scale and rotate about the pivot, then translate.
            t = 'translate(%s %s) translate(%s %s) rotate(%s) scale(%s %s) translate(%s %s)' % (
                transform.get('translateX', 0), transform.get('translateY', 0), px, py,
                transform.get('rotation', 0), transform.get('scaleX', 1), transform.get('scaleY', 1), -px, -py)
            out.append('<g transform="%s">' % t)
        for l in layers:
            c = lambda v: preview_color if v.startswith('#FF000000') or v == '@android:color/black' else v
            if 'fill' in l:
                op = ' fill-opacity="%s"' % l['alpha'] if l.get('alpha') is not None else ''
                if l.get('evenodd'):
                    op += ' fill-rule="evenodd"'
                out.append('<path d=%s fill="%s"%s/>' % (quoteattr(l['d']), c(l['fill']), op))
            else:
                op = ' stroke-opacity="%s"' % l['alpha'] if l.get('alpha') is not None else ''
                out.append('<path d=%s fill="none" stroke="%s" stroke-width="%s" stroke-linecap="round" '
                           'stroke-linejoin="round"%s/>' % (quoteattr(l['d']), c(l['stroke']), l['width'], op))
        if transform:
            out.append('</g>')
    out.append('</svg>')
    return '\n'.join(out)


def emit(name, size_dp, viewport, groups, tint=None):
    if isinstance(groups, list) and groups and isinstance(groups[0], dict):
        groups = [(None, groups)]
    with open(os.path.join(OUT, name + '.xml'), 'w') as f:
        f.write(vector_xml(size_dp, viewport, groups, tint))
    if PREVIEW:
        with open(os.path.join(PREVIEW, name + '.svg'), 'w') as f:
            f.write(svg(viewport, groups))


